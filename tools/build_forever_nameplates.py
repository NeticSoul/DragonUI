"""Repack original wowf 1.60.1.70532 art, extracted by FileDataID.

Usage: python tools/build_forever_nameplates.py EXTRACTED_DIRECTORY
Requires Pillow. Input files are named by their numeric FileDataID. Never writes
to the game installation. Blizzard artwork is not covered by the MIT license.
Atlas rectangles were read from this build's UiTextureAtlasMember.db2.
"""
import hashlib
import json
import struct
import sys
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'DragonUI/Textures/Nameplates/Forever'
# name, file data ID, pixel rect, logical width/height, slice margins (L/T/R/B)
REGIONS = [
    ('barBg', 8165540, (175, 1, 439, 39), (132, 19), (12, 7, 10, 11)),
    ('barFill', 8165540, (175, 75, 423, 95), (124, 10), (4, 5, 4, 4)),
    ('selected', 8165540, (175, 41, 439, 73), (132, 16), (8, 7, 8, 7)),
    ('deselected', 7241122, (1, 136, 211, 148), (210, 12), (5, 5, 5, 5)),
    ('levelBg', 8165536, (97, 55, 127, 85), (15, 15), (6, 6, 5, 5)),
    ('levelSelected', 8165536, (1, 55, 57, 99), (28, 22), (7, 7, 7, 7)),
    ('levelSkull', 8165536, (1, 1, 53, 53), (26, 26), (0, 0, 0, 0)),
    ('castBg', 8311982, (1, 188, 423, 214), (211, 13), (0, 0, 0, 0)),
    ('castFrame', 8311982, (422, 1, 848, 31), (213, 15), (12, 6, 12, 6)),
    ('castGlow', 8311982, (1, 124, 427, 154), (213, 15), (0, 0, 0, 0)),
    ('castGlowChannel', 8311982, (429, 92, 855, 122), (213, 15), (0, 0, 0, 0)),
    ('castShield', 1300837, (238, 30, 252, 46), (14, 16), (0, 0, 0, 0)),
    # The native pip is tiled with caps that do not fit a thin nameplate.
    # Keep its central 10x4 band and stretch it into the native 4x12 pip.
    ('castSpark', 8311982, (78, 436, 88, 440), (10, 4), (0, 0, 0, 0)),
]
FILLS = {
    'standard': (421, 264, 839, 286),
    'channel': (1, 264, 419, 286),
    'interrupted': (1, 336, 419, 358),
    'uninterruptible': (421, 384, 839, 406),
}

def load(source, fileid):
    path = source / str(fileid)
    data = path.read_bytes()
    if data[:4] == b'BLP2' and data[8] == 3:
        w, h, off = struct.unpack_from('<3I', data, 12)
        return Image.frombytes('RGBA', (w, h), data[off:off+w*h*4], 'raw', 'BGRA')
    return Image.open(path).convert('RGBA')

def main(source):
    OUT.mkdir(parents=True, exist_ok=True)
    rows, provenance = [], []
    for name, fileid, rect, logical, margins in REGIONS:
        crop = load(source, fileid).crop(rect)
        w, h = crop.size
        pw, ph = 1 << (w-1).bit_length(), 1 << (h-1).bit_length()
        padded = Image.new('RGBA', (pw, ph))
        padded.paste(crop)
        padded.save(OUT / (name + '.tga'))
        vals = [0, w/pw, 0, h/ph, *logical, *margins]
        rows.append('    forever_' + name + ' = { F .. "' + name + '", ' + ', '.join(f'{v:.9g}' for v in vals) + ' },')
        provenance.append(dict(name=name, fileDataID=fileid, rect=rect, logicalSize=logical, margins=margins))
    for name, rect in FILLS.items():
        load(source, 8311982).crop(rect).resize((512, 32), Image.Resampling.LANCZOS).save(OUT / ('cast-fill-' + name + '.tga'))
        provenance.append(dict(name='cast-fill-' + name, fileDataID=8311982, rect=rect, resized=[512,32]))
    lua = '''-- Copyright (c) 2026 NeticSoul. Licensed under the MIT License; see LICENSE.
-- Generated by tools/build_forever_nameplates.py from local wowf 1.60.1.70532.
-- Original artwork is copyright Blizzard Entertainment; see THIRD_PARTY_NOTICES.md.
local addon = select(2, ...)
local A = addon.Nameplates.atlas
local F = "Interface\\\\AddOns\\\\DragonUI\\\\Textures\\\\Nameplates\\\\Forever\\\\"

local keys = {
''' + '\n'.join(rows) + '''
}
A.FOREVER_KEYS = {}
for key, value in pairs(keys) do
    A.KEYS[key] = value
    A.FOREVER_KEYS[string.sub(key, 9)] = key
end
A.FOREVER_CAST_FILL = {
    standard = F .. "cast-fill-standard",
    channel = F .. "cast-fill-channel",
    interrupted = F .. "cast-fill-interrupted",
    uninterruptible = F .. "cast-fill-uninterruptible",
}
'''
    (ROOT / 'DragonUI/modules/nameplates/core/forever_atlas.lua').write_text(lua, encoding='utf-8')
    ids = sorted({r['fileDataID'] for r in provenance})
    manifest = dict(product='wowf', build='1.60.1.70532', sourceFiles={str(i):hashlib.sha256((source/str(i)).read_bytes()).hexdigest() for i in ids}, regions=provenance)
    (OUT / 'provenance.json').write_text(json.dumps(manifest, indent=2)+'\n', encoding='utf-8')
    print('Wrote', len(REGIONS)+len(FILLS), 'original-art textures and Forever atlas')

if __name__ == '__main__':
    main(Path(sys.argv[1]))
